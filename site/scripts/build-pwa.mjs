#!/usr/bin/env node
/**
 * Phase 8 — generate the service worker into dist/.
 *
 * Generated rather than hand-written and dropped in `public/`, because the
 * precache list has to name the content-hashed CSS bundle, and that filename
 * changes whenever the stylesheet does. A hand-maintained list would go stale
 * silently and the first symptom would be an installed app serving a page with
 * no styles.
 *
 * D15 governs what goes in the cache:
 *
 *   - **Precache the text.** All HTML, the stylesheet, the Pagefind index and
 *     the icons. About 5 MB, which is the high-value low-risk half — a reader
 *     with the text offline has the thing they came for.
 *   - **Never precache audio.** ~1.2 GB. There is no audio yet (Phase 5 is
 *     parked), but the exclusion is written now so it is not forgotten when
 *     there is.
 *   - **Never precache the EPUBs either.** They are 2.3 MB of downloads whose
 *     whole purpose is to be saved into another app. Caching them would double
 *     the storage for no benefit.
 *
 * Strategy is network-first for documents, cache-first for immutable assets.
 * Network-first matters for this corpus specifically: it corrects itself often,
 * and a reader holding a stale cached page is a reader acting on a defect that
 * has already been fixed.
 */

import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { readdir } from 'node:fs/promises';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const HERE = dirname(fileURLToPath(import.meta.url));
const DIST = join(HERE, '..', 'dist');

/** Everything a reader needs to read the corpus with no signal. */
const PRECACHE_INCLUDE = [
  /\.html$/,
  /^_astro\/.*\.css$/,
  /^pagefind\/.*\.(js|json|pf_meta|pf_index|pf_fragment|pagefind)$/,
  /^icons\/.*\.png$/,
  // Root-level scripts: theme init, theme toggle, header shortcuts, search,
  // the SW registration itself. These moved out of the page when the CSP
  // stopped permitting inline scripts, so without precaching them an offline
  // reader loses the theme toggle and the search shortcut.
  /^[^/]+\.js$/,
  /^favicon\.svg$/,
  /^manifest\.webmanifest$/,
];

/** Never cached, whatever else matches. Order matters: exclusions win. */
const PRECACHE_EXCLUDE = [
  /^audio\//,          // Phase 5. ~1.2 GB when it exists — D15 says opt-in, never precache
  /^downloads\/.*\.epub$/,
  /^downloads\/markdown\//,
  // A service worker must never precache itself: the browser manages sw.js
  // updates, and a cached copy can pin the worker to an old version that then
  // serves its own stale self. It escapes the root-.js rule today only because
  // the build cleans dist/ first, so sw.js does not exist when this walks —
  // which is luck, not design. Stated explicitly.
  /^sw\.js$/,
];

async function walk(dir, base = dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full, base)));
    else out.push(relative(base, full).split('\\').join('/'));
  }
  return out;
}

/**
 * dist path -> the URL a browser will request.
 *
 * The root is the case to watch: `index.html` has no leading directory, so a
 * bare `endsWith('/index.html')` test misses it and the home page precaches as
 * `/index.html`. The site serves it at `/`, and the offline fallback looks for
 * `/`, so that mismatch silently costs the fallback its last resort.
 */
const urlFor = (rel) => {
  if (rel === 'index.html') return '/';
  if (rel.endsWith('/index.html')) return '/' + rel.slice(0, -'index.html'.length);
  return '/' + rel;
};

async function main() {
  if (!existsSync(DIST)) {
    console.error('build-pwa: dist/ not found — run after `astro build`.');
    process.exit(2);
  }

  const files = await walk(DIST);
  const precache = files
    .filter((f) => PRECACHE_INCLUDE.some((re) => re.test(f)))
    .filter((f) => !PRECACHE_EXCLUDE.some((re) => re.test(f)))
    .map(urlFor)
    .sort();

  const bytes = files
    .filter((f) => precache.includes(urlFor(f)))
    .reduce((n, f) => n + statSync(join(DIST, f)).size, 0);

  // Cache name derives from the precache list, so a content change ships a new
  // cache and the old one is deleted on activate. No manual version bumping.
  const version = createHash('sha256').update(precache.join('\n')).digest('hex').slice(0, 12);

  const sw = `/* Generated by scripts/build-pwa.mjs — do not edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = 'lih-' + VERSION;
const PRECACHE = ${JSON.stringify(precache, null, 2)};
const OFFLINE_URL = '/offline/';

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // addAll is atomic — one 404 fails the whole install. Add individually so a
    // single missing asset degrades instead of leaving the reader with nothing.
    await Promise.all(PRECACHE.map(async (url) => {
      try { await cache.add(new Request(url, { cache: 'reload' })); }
      catch (e) { console.warn('[sw] precache miss', url, e); }
    }));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith('lih-') && key !== CACHE) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Download *files* and audio stream from the network, always: they are large
  // and meant to be saved into another app, not held twice.
  //
  // The trailing-slash test is load-bearing. Excluding all of /downloads/ also
  // excluded the /downloads/ *page*, so respondWith never ran for it — no cached
  // copy and no offline fallback, on the one page /offline/ tells the reader to
  // go to. Files have an extension; the page ends in a slash.
  const isBulkFile =
    (url.pathname.startsWith('/downloads/') && !url.pathname.endsWith('/')) ||
    url.pathname.startsWith('/audio/');
  if (isBulkFile) return;

  // Documents: network first, so a corrected page reaches the reader.
  if (request.mode === 'navigate' || request.destination === 'document') {
    event.respondWith((async () => {
      try {
        const fresh = await fetch(request);
        // Only cache a good response. Without this a transient 404 or 5xx
        // overwrites the precached copy of a real page, and the reader then
        // gets that error page back when they are offline — the cache turning
        // a momentary blip into a permanent one.
        if (fresh.ok) (await caches.open(CACHE)).put(request, fresh.clone());
        return fresh;
      } catch {
        const cached = await caches.match(request);
        if (cached) return cached;
        const home = await caches.match('/');
        return (await caches.match(OFFLINE_URL)) || home ||
          new Response('Offline', { status: 503, headers: { 'Content-Type': 'text/plain' } });
      }
    })());
    return;
  }

  // Assets: cache first. The CSS and Pagefind files are content-hashed, so a
  // cached copy is never the wrong copy.
  event.respondWith((async () => {
    const cached = await caches.match(request);
    if (cached) return cached;
    try {
      const fresh = await fetch(request);
      if (fresh.ok) (await caches.open(CACHE)).put(request, fresh.clone());
      return fresh;
    } catch {
      return cached || Response.error();
    }
  })());
});
`;

  writeFileSync(join(DIST, 'sw.js'), sw);
  console.log(
    `build-pwa: sw.js — ${precache.length} precached URLs, ` +
    `${(bytes / 1024 / 1024).toFixed(1)} MB, cache lih-${version}`
  );
}

main();
